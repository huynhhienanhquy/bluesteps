#!/usr/bin/env pwsh
<#
.SYNOPSIS
    Build, check, or validate Codex Agent Kit without requiring Python.
.DESCRIPTION
    Provides a PowerShell-native fallback for Windows workstations. When Python
    is installed, the Python commands remain the canonical implementation used
    by CI and the test suite.
.PARAMETER Command
    One of build, check, or validate. Defaults to validate.
.PARAMETER Profile
    Select and persist a profile from profiles/*.json before building.
.PARAMETER Guide
    Select and persist one or more framework guides before building.
.PARAMETER ClearGuides
    Persist an empty guide list before building.
.PARAMETER MaxAgentsBytes
    Positive byte budget to persist for generated AGENTS.md.
#>
param(
    [ValidateSet('build', 'check', 'validate')]
    [string]$Command = 'validate',
    [string]$Profile,
    [string[]]$Guide,
    [switch]$ClearGuides,
    [int]$MaxAgentsBytes
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$script:Root = Split-Path -Parent $PSScriptRoot
$script:Utf8NoBom = New-Object System.Text.UTF8Encoding($false)
$script:Targets = @(
    @{ Path = '.cursorrules'; Header = '' },
    @{ Path = '.clinerules'; Header = '' },
    @{
        Path = '.github/copilot-instructions.md'
        Header = "# GitHub Copilot Instructions`n`nAuto-generated by scripts/build_agents_md.py.`nDo not edit manually.`n`n"
    }
)

function Read-KitJson {
    <# Read a UTF-8 JSON object and return its PowerShell representation. #>
    param([Parameter(Mandatory)][string]$Path)
    return Get-Content -LiteralPath $Path -Raw -Encoding UTF8 | ConvertFrom-Json
}

function Write-Utf8File {
    <# Replace a text file using UTF-8 without a byte-order mark. #>
    param(
        [Parameter(Mandatory)][string]$Path,
        [Parameter(Mandatory)][AllowEmptyString()][string]$Content
    )
    $parent = Split-Path -Parent $Path
    if ($parent -and -not (Test-Path -LiteralPath $parent)) {
        New-Item -ItemType Directory -Force -Path $parent | Out-Null
    }
    [System.IO.File]::WriteAllText($Path, $Content, $script:Utf8NoBom)
}

function Get-KitSettings {
    <# Load normalized profile, guide, and byte-budget settings. #>
    $path = Join-Path $script:Root '.agent-kit.json'
    $raw = if (Test-Path -LiteralPath $path) { Read-KitJson $path } else { [pscustomobject]@{} }
    $profileName = if ($raw.PSObject.Properties.Name -contains 'profile') { [string]$raw.profile } else { 'lean' }
    $guideNames = if ($raw.PSObject.Properties.Name -contains 'guides') { @($raw.guides) } else { @() }
    $budget = if ($raw.PSObject.Properties.Name -contains 'max_agents_bytes') { [int]$raw.max_agents_bytes } else { 32768 }
    if ([string]::IsNullOrWhiteSpace($profileName)) { throw 'profile must be a non-empty string' }
    if ($budget -le 0) { throw 'max_agents_bytes must be positive' }
    return [ordered]@{ profile = $profileName; guides = @($guideNames); max_agents_bytes = $budget }
}

function Resolve-KitProfile {
    <# Resolve profile inheritance into a stable, de-duplicated rule list. #>
    param(
        [Parameter(Mandatory)][string]$Name,
        [string[]]$Stack = @()
    )
    if ($Stack -contains $Name) { throw "Profile inheritance cycle: $($Stack + $Name -join ' -> ')" }
    $path = Join-Path $script:Root "profiles/$Name.json"
    if (-not (Test-Path -LiteralPath $path)) { throw "Unknown profile: $Name" }
    $profileData = Read-KitJson $path
    $resolved = [System.Collections.Generic.List[string]]::new()
    if ($profileData.PSObject.Properties.Name -contains 'extends') {
        foreach ($item in Resolve-KitProfile -Name ([string]$profileData.extends) -Stack ($Stack + $Name)) {
            if (-not $resolved.Contains($item)) { $resolved.Add($item) }
        }
    }
    if ($profileData.rules -is [string] -and $profileData.rules -eq 'all') {
        $declared = Get-ChildItem -LiteralPath (Join-Path $script:Root 'rules') -Directory |
            Where-Object { Test-Path -LiteralPath (Join-Path $_.FullName 'RULE.md') } |
            Sort-Object Name | ForEach-Object Name
    } else {
        $declared = @($profileData.rules)
    }
    foreach ($item in $declared) {
        $ruleName = [string]$item
        if (-not (Test-Path -LiteralPath (Join-Path $script:Root "rules/$ruleName/RULE.md"))) {
            throw "Profile $Name references missing rule: $ruleName"
        }
        if (-not $resolved.Contains($ruleName)) { $resolved.Add($ruleName) }
    }
    return @($resolved)
}

function Resolve-KitGuides {
    <# Resolve configured guide names to safe, existing Markdown paths. #>
    param([string[]]$Names)
    $paths = @()
    foreach ($rawName in $Names) {
        $name = ([string]$rawName) -replace '\.md$', ''
        if ($name -notmatch '^[a-zA-Z0-9-]+$') { throw "Invalid guide name: $rawName" }
        $path = Join-Path $script:Root "guides/$name.md"
        if (-not (Test-Path -LiteralPath $path)) { throw "Unknown guide: $rawName" }
        $paths += Get-Item -LiteralPath $path
    }
    return $paths
}

function Get-MarkdownSource {
    <# Read Markdown using UTF-8 and normalize source text for generation. #>
    param([Parameter(Mandatory)][string]$Path)
    return (Get-Content -LiteralPath $Path -Raw -Encoding UTF8).Replace("`r`n", "`n").Trim([char[]]" `t`r`n")
}

function Get-KitOutputs {
    <# Render expected instruction files for the active profile without writing. #>
    param([Parameter(Mandatory)][System.Collections.IDictionary]$Settings)
    $rules = @(Resolve-KitProfile -Name $Settings.profile)
    $guides = @(Resolve-KitGuides -Names $Settings.guides)
    $rows = foreach ($ruleName in $rules) {
        $path = Join-Path $script:Root "rules/$ruleName/RULE.md"
        $lines = Get-Content -LiteralPath $path -Encoding UTF8
        $titleLine = $lines | Where-Object { $_ -like '# *' } | Select-Object -First 1
        $title = if ($titleLine) { $titleLine.Substring(2) } else { $ruleName }
        $purpose = ''
        $purposeIndex = [Array]::IndexOf([string[]]$lines, '## Purpose')
        if ($purposeIndex -ge 0 -and $purposeIndex + 1 -lt $lines.Count) { $purpose = $lines[$purposeIndex + 1].Trim() }
        "| [$title](#rule-$ruleName) | $purpose |"
    }
    $guideSummary = if ($guides.Count) { ($guides | ForEach-Object BaseName) -join ', ' } else { 'none' }
    $introLines = [System.Collections.Generic.List[string]]::new()
    @(
        '# AGENTS.md', '',
        'This file is generated. Edit `.agent-kit.json`, `profiles/`, `rules/`, or `guides/`, then rebuild.',
        "Active profile: ``$($Settings.profile)``. Active guides: $guideSummary.", '',
        '## Quick Reference', '', '| Rule | Purpose |', '|------|---------|'
    ) | ForEach-Object { $introLines.Add($_) }
    $rows | ForEach-Object { $introLines.Add($_) }
    @(
        '', '## Project Adaptation', '',
        '- Read only the repository context required for the current task.',
        "- Discover and use the repository's actual package manager and commands.",
        '- Follow verified local architecture, naming, formatting, and test conventions.',
        '- Put framework or subtree-specific guidance in the closest nested `AGENTS.md`.',
        '- Apply `definition-of-done.md` only to applicable implementation work.'
    ) | ForEach-Object { $introLines.Add($_) }
    $intro = $introLines -join "`n"
    $sections = foreach ($ruleName in $rules) {
        $source = "rules/$ruleName/RULE.md"
        "<!-- source: $source -->`n<a id=`"rule-$ruleName`"></a>`n`n$(Get-MarkdownSource (Join-Path $script:Root $source))"
    }
    foreach ($guidePath in $guides) {
        $source = "guides/$($guidePath.BaseName).md"
        $sections += "<!-- source: $source -->`n<a id=`"guide-$($guidePath.BaseName)`"></a>`n`n$(Get-MarkdownSource $guidePath.FullName)"
    }
    $separator = "`n`n---`n`n"
    $agents = (@($intro) + @($sections)) -join $separator
    $agents += "`n"
    $bytes = [System.Text.Encoding]::UTF8.GetByteCount($agents)
    if ($bytes -gt [int]$Settings.max_agents_bytes) {
        throw "Generated AGENTS.md is $bytes bytes; budget is $($Settings.max_agents_bytes) bytes"
    }
    $body = ($sections -join $separator) + "`n"
    $outputs = [ordered]@{ 'AGENTS.md' = $agents }
    $outputs['CLAUDE.md'] = "# Claude Code Instructions`n`n<!-- Generated by scripts/build_agents_md.py; do not edit manually. -->`n`n@AGENTS.md`n"
    foreach ($target in $script:Targets) { $outputs[$target.Path] = $target.Header + $body }
    return $outputs
}

function Get-KitManifest {
    <# Build the deterministic distributable path inventory used by the kit. #>
    $rootPrefix = $script:Root.TrimEnd('\', '/') + [System.IO.Path]::DirectorySeparatorChar
    [string[]]$entries = Get-ChildItem -LiteralPath $script:Root -Force -Recurse |
        Where-Object {
            $relativeParts = $_.FullName.Substring($rootPrefix.Length) -split '[\\/]'
            ($relativeParts -notcontains '.git') -and ($relativeParts -notcontains '__pycache__')
        } |
        ForEach-Object {
            $relative = $_.FullName.Substring($rootPrefix.Length).Replace('\', '/')
            if ($_.PSIsContainer) { "$relative/" } else { $relative }
        }
    [Array]::Sort($entries, [System.StringComparer]::Ordinal)
    return ($entries -join "`n") + "`n"
}

function Save-KitSettings {
    <# Persist normalized settings after an explicit profile or guide change. #>
    param([Parameter(Mandatory)][System.Collections.IDictionary]$Settings)
    $profileJson = ConvertTo-Json -InputObject ([string]$Settings.profile) -Compress
    $guidesJson = ConvertTo-Json -InputObject @($Settings.guides) -Compress
    $json = "{`n  `"profile`": $profileJson,`n  `"guides`": $guidesJson,`n  `"max_agents_bytes`": $($Settings.max_agents_bytes)`n}`n"
    Write-Utf8File -Path (Join-Path $script:Root '.agent-kit.json') -Content $json
}

function Invoke-KitBuild {
    <# Generate instructions and manifest from the selected project settings. #>
    param([Parameter(Mandatory)][System.Collections.IDictionary]$Settings)
    $outputs = Get-KitOutputs -Settings $Settings
    foreach ($entry in $outputs.GetEnumerator()) {
        Write-Utf8File -Path (Join-Path $script:Root $entry.Key) -Content $entry.Value
    }
    $manifestPath = Join-Path $script:Root 'MANIFEST.txt'
    if (-not (Test-Path -LiteralPath $manifestPath)) { Write-Utf8File -Path $manifestPath -Content '' }
    Write-Utf8File -Path $manifestPath -Content (Get-KitManifest)
    Write-Host "Generated $($outputs.Count) instruction files with profile $($Settings.profile) and refreshed MANIFEST.txt."
}

function Test-KitGeneratedFiles {
    <# Return stale generated files without changing repository content. #>
    param([Parameter(Mandatory)][System.Collections.IDictionary]$Settings)
    $failures = @()
    foreach ($entry in (Get-KitOutputs -Settings $Settings).GetEnumerator()) {
        $path = Join-Path $script:Root $entry.Key
        if (-not (Test-Path -LiteralPath $path) -or (Get-Content -LiteralPath $path -Raw -Encoding UTF8).Replace("`r`n", "`n") -cne $entry.Value) {
            $failures += "Stale generated file: $($entry.Key)"
        }
    }
    return $failures
}

function Test-KitStructure {
    <# Validate generated outputs and the most important portable kit contracts. #>
    param([Parameter(Mandatory)][System.Collections.IDictionary]$Settings)
    $failures = @(Test-KitGeneratedFiles -Settings $Settings)
    $requiredSkills = @('accessibility', 'agent-orchestration', 'api-design', 'backend-api-workflow', 'bug-investigation', 'ci-troubleshooting', 'code-review', 'database-migration', 'dependency-upgrade', 'feature-implementation', 'frontend-workflow', 'llm-integration', 'logging-monitoring', 'performance-investigation', 'performance-optimization', 'refactoring', 'release-readiness', 'repository-onboarding', 'security-audit', 'task-planning', 'test-engineering', 'vibe-development')
    foreach ($name in $requiredSkills) {
        $path = Join-Path $script:Root ".agents/skills/$name/SKILL.md"
        if (-not (Test-Path -LiteralPath $path)) { $failures += "Missing required skill: $name"; continue }
        $text = Get-Content -LiteralPath $path -Raw -Encoding UTF8
        foreach ($section in @('## Guardrails', '## Definition of done')) {
            if ($text -notmatch "(?m)^$([regex]::Escape($section))\s*$") { $failures += "Missing $section in skill: $name" }
        }
    }
    foreach ($critical in @('scope-and-authority', 'execution-safety', 'security', 'verification')) {
        if ((Resolve-KitProfile -Name 'lean') -notcontains $critical) { $failures += "Lean profile omits critical rule: $critical" }
    }
    foreach ($relative in @('evals/behavior-cases.json', 'evals/behavior-catalog.json', 'evals/fixtures/perfect-responses.json')) {
        $fixture = Join-Path $script:Root $relative
        if (-not (Test-Path -LiteralPath $fixture)) { $failures += "Missing behavioral evaluation artifact: $relative" } else { $null = Read-KitJson $fixture }
    }
    if (-not (Test-Path -LiteralPath (Join-Path $script:Root 'scripts/run_behavior_evals.mjs'))) {
        $failures += 'Missing behavioral evaluation runner'
    }
    return $failures
}

try {
    $settings = Get-KitSettings
    $hasOverrides = $PSBoundParameters.ContainsKey('Profile') -or $PSBoundParameters.ContainsKey('Guide') -or $ClearGuides -or $PSBoundParameters.ContainsKey('MaxAgentsBytes')
    if ($Command -ne 'build' -and $hasOverrides) { throw 'Profile and guide options are only valid with the build command' }
    if ($Profile) { $settings.profile = $Profile }
    if ($PSBoundParameters.ContainsKey('MaxAgentsBytes')) {
        if ($MaxAgentsBytes -le 0) { throw '-MaxAgentsBytes must be positive' }
        $settings.max_agents_bytes = $MaxAgentsBytes
    }
    if ($ClearGuides) {
        $settings.guides = @()
    } elseif ($PSBoundParameters.ContainsKey('Guide')) {
        $expandedGuides = foreach ($item in $Guide) { $item -split ',' }
        $settings.guides = @($expandedGuides | Where-Object { $_ } | Select-Object -Unique)
    }
    if ($hasOverrides) {
        $null = Resolve-KitProfile -Name $settings.profile
        $null = Resolve-KitGuides -Names $settings.guides
        Save-KitSettings -Settings $settings
    }
    if ($Command -eq 'build') { Invoke-KitBuild -Settings $settings; exit 0 }
    $errors = @(if ($Command -eq 'check') { Test-KitGeneratedFiles -Settings $settings } else { Test-KitStructure -Settings $settings })
    if ($errors.Count) {
        $errors | ForEach-Object { Write-Error $_ -ErrorAction Continue }
        exit 1
    }
    Write-Host $(if ($Command -eq 'check') { 'Generated instruction files are current and within budget.' } else { 'Codex Agent Kit validation passed.' })
    exit 0
} catch {
    Write-Error "Kit command failed: $($_.Exception.Message)"
    exit 1
}
